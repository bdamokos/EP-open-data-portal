export function proposalRegion(text,language){if(!indexes.has(language)){const index=new Map();for(const[role,headings]of Object.entries(REGION_HEADINGS[language]??{}))for(const heading of headings)index.set(fold(heading),role);indexes.set(language,index);}return indexes.get(language).get(fold(text))??null;}
