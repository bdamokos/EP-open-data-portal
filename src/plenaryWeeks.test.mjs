import test from 'node:test';
import assert from 'node:assert/strict';
import {createElement,act} from 'react';
import {Window} from 'happy-dom';
import {freshLoader} from './test-support/viteRunner.mjs';

test('all plenary defaults use weeks while exact item links, single days and history keep their scope',async t=>{
  const window=new Window({url:'http://localhost/?view=legislation&pl-mode=cloud&pl-sitting=MTG-PL-2026-10-07'});
  const globals={window,document:window.document,location:window.location,history:window.history,Event:window.Event,HTMLElement:window.HTMLElement,HTMLButtonElement:window.HTMLButtonElement,innerWidth:390,IS_REACT_ACT_ENVIRONMENT:true};
  const originals=new Map(Object.keys(globals).map(key=>[key,Object.getOwnPropertyDescriptor(globalThis,key)]));
  for(const [key,value] of Object.entries(globals))Object.defineProperty(globalThis,key,{value,configurable:true,writable:true});
  let loadModule,root;
  t.after(async()=>{if(root)await act(async()=>root.unmount());await window.happyDOM.close();for(const [key,descriptor] of originals)descriptor?Object.defineProperty(globalThis,key,descriptor):delete globalThis[key];});
  const days=['2026-10-07','2026-10-08','2026-10-19'],sittings=days.map(date=>({id:'MTG-PL-'+date,date,phase:date==='2026-10-19'?'upcoming':'past'}));
  const topicFor=day=>({id:day.id+'-OJ-ITM-D-1',sittingId:day.id,date:day.date,title:'Debate on '+day.date,kind:'PLENARY_DEBATE',documentIds:[],procedureIds:[]});
  const calls=[];
  t.mock.method(globalThis,'fetch',async input=>{
    const url=new URL(input,window.location.href),p=url.searchParams;calls.push(url);
    if(url.pathname.endsWith('/insights/legislation')) {
      const week=p.has('week')?(p.get('week')==='latest'?'2026-10-05':p.get('week')):null;
      const selected=week?sittings.filter(s=>week==='2026-10-05'?s.date<'2026-10-19':s.date==='2026-10-19'):[sittings.find(s=>s.id===p.get('sitting'))||sittings[1]];
      const topics=selected.map(topicFor),topic=topics.find(topic=>topic.id===p.get('topic'));
      return Response.json({view:'legislation',week,sitting:selected[0],sittings,topics,agendaSittings:week?selected.map(s=>({...s,agendaComplete:true,agendaError:null})):undefined,coverage:{agendaError:null},detail:topic?{...topic,phase:'past',procedures:[],committeeWork:[],roles:[],speeches:[],people:[],stats:{denominator:0,dimensions:{country:[],group:[],gender:[],age:[]}},coverage:{gaps:[],speechAssociations:{sources:[],truncated:false}},voteCoverage:{truncated:false}}:null});
    }
    if(url.pathname.endsWith('/insights/speech-cloud'))return Response.json({scope:{kind:p.has('week')?'week':'sitting',phase:p.get('week')==='2026-10-19'?'upcoming':'past'},words:[],speeches:[],coverage:{transcripts:0,complete:true},window:{start:null,end:null},nextPage:null});
    if(url.pathname.endsWith('/insights/participation'))return Response.json({topics:[],series:[],window:{start:'2026-10-05',end:'2026-10-11'},coverage:{gaps:[]}});
    throw new Error('Unexpected request: '+url);
  });
  loadModule=await freshLoader(t,{configFile:false,server:{middlewareMode:true,hmr:false,watch:null},optimizeDeps:{noDiscovery:true},oxc:{jsx:{runtime:'automatic'}}});
  const {Legislation}=await loadModule('/src/Legislation.tsx');
  const {createRoot}=await import('react-dom/client');
  const container=document.createElement('div');document.body.append(container);root=createRoot(container);
  await act(async()=>root.render(createElement(Legislation,{language:'en',onBack(){}})));
  const period=()=>container.querySelector('.insight-controls select,.explorer-cloud-controls select');
  const click=async text=>act(async()=>{const button=[...container.querySelectorAll('button')].find(b=>b.textContent===text);assert(button,'Missing '+text);button.click();});
  const choose=async value=>act(async()=>{const select=period();select.value=value;select.dispatchEvent(new window.Event('change',{bubbles:true}));});
  const last=path=>calls.filter(url=>url.pathname.endsWith('/insights/'+path)).at(-1);
  assert.equal(period().value,'sitting:MTG-PL-2026-10-07');
  assert.equal(last('speech-cloud').searchParams.get('sitting'),'MTG-PL-2026-10-07');
  assert.equal(last('speech-cloud').searchParams.has('week'),false,'legacy cloud links must keep their original single-day scope');
  await act(async()=>{history.replaceState(null,'','/?view=legislation');window.dispatchEvent(new window.Event('popstate'));});
  assert.equal(last('legislation').searchParams.get('week'),'latest');
  assert.equal(period().value,'week:2026-10-05');
  assert.equal(container.querySelectorAll('.insight-agenda h3').length,2);
  await click('Word cloud');assert.equal(last('speech-cloud').searchParams.get('week'),'2026-10-05');
  await click('Agenda');
  await click('DebateDebate on 2026-10-08');
  assert.equal(new URL(location.href).searchParams.get('agenda-period'),'week:2026-10-05','opening a topic pins its concrete week for saved links');
  assert.equal(last('legislation').searchParams.get('sitting'),'MTG-PL-2026-10-08');
  assert.equal(container.querySelector('.insight-topic-detail h2').textContent,'Debate on 2026-10-08');
  assert.equal(container.querySelector('.insight-agenda-view').dataset.topicSelected,'true');
  const selectedCard=container.querySelector('.insight-agenda button[aria-pressed=true]');
  assert.equal(document.activeElement,container.querySelector('.insight-topic-detail'),'mobile selection moves keyboard focus into the detail');
  await click('Back to agenda');
  await act(async()=>new Promise(resolve=>window.requestAnimationFrame(resolve)));
  assert.equal(container.querySelector('.insight-agenda-view').dataset.topicSelected,'false');
  assert.equal(document.activeElement,selectedCard,'return restores focus to the agenda item');
  assert.equal(new URL(location.href).searchParams.has('agenda-topic'),false);
  assert.equal(period().value,'week:2026-10-05','return preserves the week');
  await act(async()=>{const popped=new Promise(resolve=>window.addEventListener('popstate',resolve,{once:true}));history.back();await popped;});
  assert.equal(container.querySelector('.insight-agenda-view').dataset.topicSelected,'true','browser Back restores the exact item');
  assert.equal(container.querySelector('.insight-topic-detail h2').textContent,'Debate on 2026-10-08');
  await choose('sitting:MTG-PL-2026-10-07');
  assert.equal(period().value,'sitting:MTG-PL-2026-10-07');
  assert.equal(container.querySelectorAll('.insight-agenda button').length,1);
  await click('Word cloud');assert.equal(period().value,'sitting:MTG-PL-2026-10-07');
  await choose('sitting:MTG-PL-2026-10-08');assert.equal(last('speech-cloud').searchParams.get('sitting'),'MTG-PL-2026-10-08');
  await act(async()=>{const popped=new Promise(resolve=>window.addEventListener('popstate',resolve,{once:true}));history.back();await popped;});
  assert.equal(period().value,'sitting:MTG-PL-2026-10-07');
  await click('What’s hot');assert.equal(last('participation').searchParams.get('week'),'2026-10-05');
  await click('Agenda');await choose('week:2026-10-19');await click('Word cloud');
  assert.equal(period().value,'week:2026-10-19');assert.equal(last('speech-cloud').searchParams.get('week'),'2026-10-19');
  assert.match(container.textContent,/This plenary week has not taken place/);
});
