"""Generate worldMap.ts from Natural Earth public-domain GeoJSON.
Usage: python3 scripts/world-map.py countries.geojson tiny.geojson src/worldMap.ts
Sources: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_tiny_countries.geojson
Equal Earth; rounding only. Never simplify countries independently.
"""
import json
import math
import sys
from pathlib import Path
A1,A2,A3,A4=1.340264,-0.081106,0.000893,0.003796
M=math.sqrt(3)/2
def equal_earth(lon,lat):
    t=math.asin(M*math.sin(math.radians(lat)));t2=t*t;t6=t2**3
    return (math.radians(lon)*math.cos(t)/(M*(A1+3*A2*t2+t6*(7*A3+9*A4*t2))),t*(A1+A2*t2+t6*(A3+A4*t2)))
scale=1000/(2*equal_earth(180,0)[0])
def project(lon,lat):
    x,y=equal_earth(lon,lat)
    return round(x*scale+500,1),round(487/2-y*scale,1)
def identity(properties):
    return properties['ISO_A3_EH'] if properties['ISO_A3_EH']!='-99' else properties['ADM0_A3']
def generate(countries,tiny):
    features=[]
    for feature in countries['features']:
        props=feature['properties'];code=identity(props)
        if code=='ATA':continue
        geometry=feature['geometry'];polygons=geometry['coordinates'] if geometry['type']=='MultiPolygon' else [geometry['coordinates']]
        paths=[]
        for polygon in polygons:
            ring=[]
            for coordinate in polygon[0]:
                point=project(*coordinate)
                if not ring or point!=ring[-1]:ring.append(point)
            if len(ring)>=4:paths.append('M'+'L'.join(f'{x:g},{y:g}' for x,y in ring)+'Z')
        if paths:features.append(dict(code=code,name=props['ADMIN'],path=''.join(paths)))
    codes={f['code'] for f in features}
    for feature in tiny['features']:
        props=feature['properties'];code=identity(props)
        if code not in codes:
            x,y=project(*feature['geometry']['coordinates']);features.append(dict(code=code,name=props['ADMIN'],x=x,y=y,path=''));codes.add(code)
    return dict(width=1000,height=487,projection='Equal Earth',source='Natural Earth 1:110m Admin 0 countries (public domain)',countries=features)
if __name__=='__main__':
    countries,tiny,out=sys.argv[1:]
    header='// Natural Earth public domain: 1:110m Admin 0 countries and 1:50m tiny countries.\n// Equal Earth projection; rounded to 0.1px without per-country simplification.\n// Generated by scripts/world-map.py from the documented Natural Earth GeoJSON sources.\n'
    Path(out).write_text(header+'export const worldMap = '+json.dumps(generate(json.loads(Path(countries).read_text()),json.loads(Path(tiny).read_text())),separators=(',',':'))+';\n')
    # Match the story reference's largest-ring centre test for the approved zoom.
    import re
    europe=set('MLT AND MCO SMR VAT LIE'.split())
    for feature in generate(json.loads(Path(countries).read_text()),json.loads(Path(tiny).read_text()))['countries']:
        best=None
        for ring in feature['path'].split('M')[1:]:
            points=[tuple(map(float,p)) for p in re.findall(r'(-?[\d.]+),(-?[\d.]+)',ring)]
            xs,ys=zip(*points);area=(max(xs)-min(xs))*(max(ys)-min(ys))
            if best is None or area>best[0]:best=(area,(max(xs)+min(xs))/2,(max(ys)+min(ys))/2)
        if best and 428<=best[1]<=664 and 12<=best[2]<=152:europe.add('1A0' if feature['code']=='KOS' else feature['code'])
    Path(out).with_name('storyEurope.mjs').write_text('// Natural Earth largest-ring centres within the approved Equal Earth zoom box.\nexport const europeStoryIso3='+json.dumps(sorted(europe))+';\n')
